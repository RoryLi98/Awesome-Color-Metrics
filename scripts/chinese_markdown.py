def code_index(d):
    from build import stats,sort_metrics,md,link,package_of
    s=stats(d)
    L=[GENERATED,'','# 实现索引','',
       f'收录 [Awesome Color Metrics](README.zh-CN.md) 中 **{s["code"]} 条带实现的记录**，包括官方、工具箱与明确标注的第三方实现。','',
       '[English](CODE.md) · [简体中文](CODE.zh-CN.md) · [中文交互网页](docs/zh-CN.html)','',
       '先按程序包列出可用函数，再按研究方向列出实现。这里核验的是发布状态，并非在当前环境安装或复现所有指标。','',
       '## 按程序包查找','','| 程序包 | 指标与函数 |','|:--|:--|']
    pk={}
    for _,p in all_metrics(d):
        for w in p.get('impl',[]):pk.setdefault(package_of(w['label']),[]).append(f'{p["name"]}（{w["label"]}）')
    for name in sorted(pk,key=lambda k:(-len(pk[k]),k.lower())):L.append(f'| **{md(name.replace("this repo","本仓库"))}** | {md("、".join(pk[name]))} |')
    L+=['','## 按研究方向查找','']
    for c in d['categories']:
        ps=[p for p in sort_metrics(d['metrics'][c['id']]) if p['status'] in CODE_STATUSES]
        if not ps:continue
        L += [f'### {c["title"]}','','| 指标 | 发表信息 | 配准要求 | 官方或第三方代码 | 其他实现 |','|:--|:--|:--|:--|:--|']
        for p in ps:
            off=link('代码'+('（第三方）' if p['status']=='unofficial' else ''),p['code']) if p.get('code') else '—'
            other='<br>'.join(link(w['label'].replace('this repo','本仓库'),w['url']) for w in p.get('impl',[])) or '—'
            align=ALIGN_ZH[p['align']][0] if p.get('align') else '不适用'
            L.append(f'| **{link(p["name"],p["paper"])}**<br><sub>{md(p["title"])}</sub> | {md(p["venue"])} {p["year"]} | {align} | {off} | {other} |')
        L.append('')
    return '\n'.join(L)
