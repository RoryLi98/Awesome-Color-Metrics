def code_cell(p):
    from build import link
    result=[]
    if p.get('code'):
        label='GitHub' if 'github.com' in p['code'] else '代码'
        label+= {'unofficial':'（第三方）','coming-soon':'（待发布）'}.get(p['status'],'')
        result.append(link(label,p['code']))
    elif p['status']=='spec':result.append('标准文档')
    elif p['status']=='coming-soon':result.append('待发布')
    if p.get('impl'):
        result.append('<sub>'+'<br>'.join(link(w['label'].replace('this repo','本仓库'),w['url']) for w in p['impl'])+'</sub>')
    return '<br>'.join(result) or '—'


def metric_cell(p):
    from build import md,link
    title=p.get('original_title',p['title'])
    out=f"**{link(title,p['paper'])}**<br>{md(p['title'])}"
    text=f"{md(p['name'])} · {md(p['tldr'])}"
    if p.get('note'):text+=f" <i>备注：{md(p['note'])}</i>"
    return out+'<br><sub>'+text+'</sub>'


