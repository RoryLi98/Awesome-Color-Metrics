# ---------------------------------------------------------------- helpers
def slug(text: str) -> str:
    """GitHub's heading anchor: lowercase, drop punctuation, spaces to hyphens."""
    s = text.strip().lower()
    s = re.sub(r'[^\w\- ]', '', s)
    return s.replace(' ', '-')


def md(text) -> str:
    """Escape text for use inside a Markdown table cell."""
    s = str(text or '')
    s = s.replace('\\', '\\\\').replace('|', '\\|').replace('*', '\\*').replace('<', '&lt;').replace('>', '&gt;')
    return re.sub(r'\s+', ' ', s).strip()


def link(label, url) -> str:
    return f'[{md(label)}]({url})'


def badge(label, value, color, target):
    lab = quote(label.replace('-', '--').replace('_', '__'))
    val = quote(str(value).replace('-', '--').replace('_', '__'))
    return f'[![{label}](https://img.shields.io/badge/{lab}-{val}-{color})]({target})'


def sort_metrics(ps):
    return sorted(ps, key=lambda p: (RANK[p['status']], -p['year'], p['name'].lower()))


def host_label(url: str) -> str:
    if 'github.com' in url:
        return 'GitHub'
    if 'sourceforge.net' in url:
        return 'SourceForge'
    return 'code'


def code_cell(p) -> str:
    st, url = p['status'], p.get('code')
    parts = []
    if url:
        label = host_label(url) + (' (unofficial)' if st == 'unofficial' else '')
        out = link(label, url)
        if p.get('framework'):
            out += f"<br><sub>{md(p['framework'])}</sub>"
        parts.append(out)
    elif st == 'spec':
        parts.append('standard')
    elif st == 'coming-soon':
        parts.append('coming soon')
    impl = p.get('impl') or []
    if impl:
        parts.append('<sub>' + '<br>'.join(link(w['label'], w['url']) for w in impl) + '</sub>')
    return '<br>'.join(parts) if parts else '—'


def metric_cell(p) -> str:
    out = f"**{link(p['name'], p['paper'])}**"
    if p['title'].strip().lower() != p['name'].strip().lower():
        out += f"<br>{md(p['title'])}"
    sub = md(p['tldr'])
    if p.get('note'):
        sub += f" <i>Note: {md(p['note'])}</i>"
    return out + f'<br><sub>{sub}</sub>'


def props_cell(p) -> str:
    col = COLOR[p['color']][0] if p.get('color') else '—'
    out = OUT_LABEL.get(p.get('output'), '')
    return md(col) + (f'<br><sub>{out}</sub>' if out else '')


def stats(d):
    ps = [p for _, p in color_data.all_metrics(d)]
    return dict(n=len(ps),
                code=sum(p['status'] in CODE_STATUSES for p in ps),
                tolerant=sum(p.get('align') in TOLERANT for p in ps),
                datasets=len(d['datasets']))


def rel(url: str, base: str) -> str:
    """Repository-relative links become absolute on the interactive page."""
    return url if re.match(r'^https?://', url) else f'{base}/blob/main/{url}'


