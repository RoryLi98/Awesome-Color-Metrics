# ---------------------------------------------------------------- CODE.md
def package_of(label: str) -> str:
    return label.split(' · ')[0].strip() if ' · ' in label else label.split(' (')[0].strip()


def code_md(d) -> str:
    cfg, s = d['config'], stats(d)
    L = [GENERATED, '', '# Code Index', '',
         f"All {s['code']} entries in [{cfg['title']}](README.md) with runnable code, first grouped by package so you can "
         f"see what one `pip install` gives you, then by section. Links checked {cfg['checked']}.", '',
         '## By Package', '', '| Package | Entries (function or metric name) |', '|:--|:--|']
    pk: dict[str, list[str]] = {}
    for c, p in color_data.all_metrics(d):
        for w in p.get('impl') or []:
            name = package_of(w['label'])
            fn = w['label'].split(' · ', 1)[1] if ' · ' in w['label'] else ''
            pk.setdefault(name, []).append(f"{p['name']}" + (f" ({fn})" if fn else ''))
    for name in sorted(pk, key=lambda k: (-len(pk[k]), k.lower())):
        L.append(f"| **{md(name)}** | {md(', '.join(pk[name]))} |")
    L += ['', '## By Section', '']
    for c in d['categories']:
        ps = [p for p in sort_metrics(d['metrics'][c['id']]) if p['status'] in CODE_STATUSES]
        if not ps:
            continue
        L += [f"### {c['title']}", '', '| Entry | Venue | Alignment | Official code | Other implementations |',
              '|:--|:--|:--|:--|:--|']
        for p in ps:
            al = ALIGN[p['align']][0] if p.get('align') else '—'
            off = link(host_label(p['code']) + (' (unofficial)' if p['status'] == 'unofficial' else ''), p['code']) if p.get('code') else '—'
            if p.get('framework') and p.get('code'):
                off += f"<br><sub>{md(p['framework'])}</sub>"
            other = '<br>'.join(link(w['label'], w['url']) for w in p.get('impl') or []) or '—'
            L.append(f"| **{link(p['name'], p['paper'])}** | {md(p['venue'])} {p['year']} | {md(al)} | {off} | {other} |")
        L.append('')
    return '\n'.join(L)


# ---------------------------------------------------------------- docs/index.html
SITE_ST = {'code': 'C', 'toolbox': 'T', 'unofficial': 'U', 'spec': 'P', 'coming-soon': 'S', 'no-code': 'N'}


def site(d) -> str:
    cfg, s = d['config'], stats(d)
    base = f"https://github.com/{cfg['owner']}/{cfg['repo']}"
    P = [dict(n=p['name'], t=p['title'], v=p['venue'], y=p['year'], c=c['id'], s=p['tldr'], p=p['paper'],
              g=p.get('code') or '', st=SITE_ST[p['status']], im=[[w['label'], rel(w['url'], base)] for w in p.get('impl') or []],
              note=p.get('note') or '', fw=p.get('framework') or '', a=p.get('align') or '', k=p.get('color') or '',
              o=p.get('output') or '') for c, p in color_data.all_metrics(d)]
    D = [[x['name'], x['year'], x.get('source') or '', x.get('capture') or '', x.get('size') or '', x['url'], x['use']]
         for x in d['datasets']]
    CATS = [dict(k=c['id'], name=c['title'], short=c['short'], desc=re.sub(r'\s+', ' ', c['description']).strip())
            for c in d['categories']]
    TR = [[t['title'], re.sub(r'\s+', ' ', t['text']).strip(), t['examples']] for t in d['trends']]
    TOOLS = [[t['name'], t['url'], t['description'], t.get('language') or '', dict(TOOL_KINDS).get(t.get('kind'))]
             for t in d['tools']]
    AL = [[a, ALIGN[a][0], ALIGN[a][1]] for a in ALIGN_ORDER]
    CO = [[k, v[0], v[1]] for k, v in COLOR.items()]
    years = [p['y'] for p in P]
    js = lambda x: json.dumps(x, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
    tpl = (ROOT / 'scripts' / 'site_template.html').read_text(encoding='utf-8')
    rep = {'__P__': js(P), '__D__': js(D), '__CATS__': js(CATS), '__TRENDS__': js(TR), '__TOOLS__': js(TOOLS),
           '__ALIGN__': js(AL), '__COLOR__': js(CO), '__OUT__': js(OUT_LABEL),
           '__NP__': str(s['n']), '__NCODE__': str(s['code']), '__NT__': str(s['tolerant']), '__ND__': str(s['datasets']),
           '__CHECKED__': cfg['checked'], '__TITLE__': cfg['title'], '__TAGLINE__': cfg['tagline'],
           '__REPO_URL__': base, '__Y0__': str(min(years)), '__Y1__': str(max(years))}
    for k, v in rep.items():
        tpl = tpl.replace(k, v)
    return tpl


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if generated files are out of date')
    args = ap.parse_args()
    d = color_data.load()
    errs = color_data.validate(d)
    if errs:
        print('Data validation failed:\n  ' + '\n  '.join(errs))
        sys.exit(1)
    outputs = {ROOT / 'README.md': readme(d), ROOT / 'CODE.md': code_md(d), ROOT / 'docs' / 'index.html': site(d)}
    stale = []
    for path, text in outputs.items():
        old = path.read_text(encoding='utf-8') if path.exists() else None
        if args.check:
            if old != text:
                stale.append(str(path.relative_to(ROOT)))
        elif old != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
            print('wrote', path.relative_to(ROOT))
    if stale:
        print('Out of date (run `python scripts/build.py` and commit):', ', '.join(stale))
        sys.exit(1)
    s = stats(d)
    print(f"ok: {s['n']} entries, {s['code']} with code, {s['tolerant']} misalignment-tolerant, {s['datasets']} datasets")


if __name__ == '__main__':
    main()
